#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""从 pci.ids 抽取 NVIDIA/AMD/Intel 三家 GPU 设备条目，生成 Rust 静态查找表。

用法（数据源手动下载，脚本不联网，保证可重现）：
  curl -o pci.ids https://pci-ids.ucw.cz/v2.2/pci.ids
  python tools/gen_pci_gpu_table.py pci.ids

产物：rust/crates/winsuitex-platform/src/pci_gpu_table.rs
  PCI_GPU_TABLE: &[(u16, u16, &str)]  # (vendor_id, device_id, 设备名)，按 ID 排序

收录口径（pci.ids 主列表不带设备类别，按名称关键词筛选三家显示设备）：
  - 10DE NVIDIA：排除 nForce/MCP 等芯片组与 USB/存储/网络设备，其余全收
    （含 RIVA/Vanta 等老卡，品牌命名千奇百怪，黑名单比白名单稳）；
  - 1002 AMD/ATI：名称含 radeon / firepro / firegl / firemv / all-in-wonder；
  - 8086 Intel：名称含 graphics / vga（核显全部命中）。

设备名清洗：`GT216 [GeForce GT 220]` 取方括号内容（芯片代号对资产盘点无意义），
无方括号用原名；连续空白折叠。未知 DEV 由运行时回退为 "NVIDIA (PCI 10DE:xxxx)"。
"""
import re
import sys
from datetime import date

SOURCE_URL = "https://pci-ids.ucw.cz/v2.2/pci.ids"
OUT = "rust/crates/winsuitex-platform/src/pci_gpu_table.rs"

VENDORS = {"10de": "NVIDIA", "1002": "AMD", "8086": "Intel"}
AMD_KW = re.compile(r"radeon|firepro|firegl|firemv|all-in-wonder", re.I)
INTEL_KW = re.compile(r"graphics|vga", re.I)
# NVIDIA 非显示设备（芯片组 / 总线 / 外设控制器）。显示芯片命名无规律可白名单，
# 用黑名单排除，宁可多收不可漏收。
NVIDIA_EXCL = re.compile(
    r"nforce|mcp|ck804|ck8-04|ion\b|smbus|ethernet|sata|ide|usb|firewire|"
    r"audio|hda|memory controller|isa bridge|host bridge|pci bridge|"
    r"pcie bridge|raid|nvram|watchdog|thermal|smu|dpu|eeprom|i2c|gpio",
    re.I,
)


def clean_name(raw: str) -> str:
    m = re.search(r"\[([^\[\]]+)\]", raw)
    name = m.group(1).strip() if m else raw.strip()
    name = re.sub(r"\s+", " ", name)
    return name


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main(path: str) -> None:
    ven_re = re.compile(r"^([0-9a-f]{4})  (.+)$")
    dev_re = re.compile(r"^\t([0-9a-f]{4})  (.+)$")
    devices = []  # (ven, dev, name)
    cur = None
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            m = ven_re.match(line.rstrip("\n"))
            if m:
                cur = m.group(1).lower()
                continue
            if cur not in VENDORS:
                continue
            m = dev_re.match(line.rstrip("\n"))
            if not m:
                continue
            dev, raw_name = m.group(1).lower(), m.group(2)
            if cur == "10de":
                if NVIDIA_EXCL.search(raw_name):
                    continue
            elif cur == "1002":
                if not AMD_KW.search(raw_name):
                    continue
            else:  # 8086
                if not INTEL_KW.search(raw_name):
                    continue
            name = clean_name(raw_name)
            if not name:
                continue
            devices.append((int(cur, 16), int(dev, 16), name))

    devices.sort(key=lambda t: (t[0], t[1]))
    seen = set()
    uniq = []
    for v, d, n in devices:
        if (v, d) in seen:
            continue
        seen.add((v, d))
        uniq.append((v, d, n))

    by_vendor = {
        VENDORS[vid_hex]: sum(1 for x in uniq if x[0] == int(vid_hex, 16))
        for vid_hex in VENDORS
    }
    lines = [
        "// AUTO-GENERATED by tools/gen_pci_gpu_table.py — do not edit by hand.",
        f"// Source: {SOURCE_URL} (pci.ids, generated {date.today().isoformat()})",
        "// 收录口径见脚本 docstring：NVIDIA 黑名单 / AMD+Intel 白名单，",
        "// 设备名取方括号内容（如 GT216 [GeForce GT 220] → GeForce GT 220）。",
        "// 查找用二分（调用方 binary_search_by_key），必须保持 (vendor, device) 升序。",
        f"// 条目数：NVIDIA {by_vendor['NVIDIA']} / AMD {by_vendor['AMD']} /"
        f" Intel {by_vendor['Intel']}，共 {len(uniq)}。",
        "pub(crate) static PCI_GPU_TABLE: &[(u16, u16, &str)] = &[",
    ]
    for v, d, n in uniq:
        lines.append(f'    (0x{v:04X}, 0x{d:04X}, "{esc(n)}"),')
    lines.append("];")
    lines.append("")

    out = "\n".join(lines)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print(f"[gen_pci_gpu_table] {len(uniq)} 条 → {OUT}")
    for vn, cnt in by_vendor.items():
        print(f"  {vn}: {cnt}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
