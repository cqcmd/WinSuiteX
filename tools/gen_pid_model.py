#!/usr/bin/env python3
"""Generate rust/crates/winsuitex-platform/src/pid_model_table.rs from inf_vidpid.json.

Produces a static &[(&str,&str,&str)] = [(vid, pid, model), ...] plus a lookup.
Run after extract_inf_vidpid.py. Committed as seed data (no build-time dep).
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC_JSON = os.path.join(HERE, "inf_vidpid.json")
OUT_RS = os.path.join(
    HERE, "..", "rust", "crates", "winsuitex-platform", "src", "pid_model_table.rs"
)


def main():
    with open(SRC_JSON, "r", encoding="utf-8") as f:
        rows = json.load(f)
    # sort by (vid, pid) for stable output + future binary search
    rows.sort(key=lambda r: (r["vid"], r["pid"]))
    lines = []
    lines.append("// AUTO-GENERATED by tools/gen_pid_model.py — do not edit by hand.")
    lines.append("// Source: D:\\jinglingResource\\Drives INF VID+PID -> model seed extraction.")
    lines.append("// Lookup chain in hid.rs: HidD_GetProductString > PID_MODEL > VID_BRAND.")
    lines.append("")
    lines.append("/// (VID, PID, model) seed entries extracted from vendor driver INF files.")
    lines.append("/// PIDs are unique within a VID for the brands present, so this resolves")
    lines.append("/// many real product names without a runtime query (offline fallback).")
    lines.append("pub(crate) static PID_MODEL: &[(&str, &str, &str)] = &[")
    for r in rows:
        vid = r["vid"]
        pid = r["pid"]
        model = r["model"].replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    ("{vid}", "{pid}", "{model}"),')
    lines.append("];")
    lines.append("")
    lines.append("/// Offline fallback: real product model for a (VID, PID) pair.")
    lines.append("/// Returns `None` when no seed exists (caller falls back to VID_BRAND).")
    lines.append("pub(crate) fn lookup_pid_model(vid: &str, pid: &str) -> Option<&'static str> {")
    lines.append("    let vid = vid.to_ascii_uppercase();")
    lines.append("    let pid = pid.to_ascii_uppercase();")
    lines.append("    PID_MODEL")
    lines.append("        .iter()")
    lines.append("        .find(|entry| entry.0 == vid.as_str() && entry.1 == pid.as_str())")
    lines.append("        .map(|(_, _, m)| *m)")
    lines.append("}")
    lines.append("")
    out = "\n".join(lines)
    with open(OUT_RS, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"wrote {OUT_RS} ({len(rows)} entries)")


if __name__ == "__main__":
    main()
