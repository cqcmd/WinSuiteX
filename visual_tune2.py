# ---- 执行 + 断言 ----
fails = []
for old, new, note in reps:
    cnt = s.count(old)
    if cnt != 1:
        fails.append((note, cnt))
        continue
    s = s.replace(old, new, 1)

if fails:
    print("ABORT - 以下替换未命中恰好 1 次：")
    for note, cnt in fails:
        print("  [%s] count=%d" % (note, cnt))
    sys.exit(1)

